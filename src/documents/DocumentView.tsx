import { useMemo, useState } from 'react';
import { hasTabularData, isNumericColumn, type DocumentBlock, type DocumentSpec } from '../../shared/document';
import { chartSvg, formatNumber } from './chart';
import { DATA_DISCLAIMER, downloadBlob, fileName } from './files';

interface DocumentViewProps {
  document: DocumentSpec;
}

const OPTION_LETTERS = 'abcdefgh';
const SCREEN_CHART_STYLE = { textColor: 'currentColor', gridColor: 'rgb(128 128 128 / 0.35)', fontFamily: 'system-ui, sans-serif' };

function Chart({ block }: { block: Extract<DocumentBlock, { type: 'chart' }> }) {
  // The markup is generated by chartSvg, which escapes every piece of text.
  const svg = useMemo(() => chartSvg(block, SCREEN_CHART_STYLE), [block]);
  const summary = block.series
    .map((series) => `${series.name}: ${block.labels.map((label, index) => `${label} ${formatNumber(series.values[index])}`).join(', ')}`)
    .join('. ');

  return (
    <figure className="doc-chart">
      {block.title && <figcaption>{block.title}</figcaption>}
      <div role="img" aria-label={`${block.title || 'Grafico'}. ${summary}`} dangerouslySetInnerHTML={{ __html: svg }} />
    </figure>
  );
}

function Block({ block, firstQuestion }: { block: DocumentBlock; firstQuestion: number }) {
  switch (block.type) {
    case 'heading':
      return <h3>{block.text}</h3>;
    case 'paragraph':
      return <p>{block.text}</p>;
    case 'list': {
      const List = block.ordered ? 'ol' : 'ul';
      return (
        <List className="doc-list">
          {block.items.map((item, index) => (
            <li key={index}>{item}</li>
          ))}
        </List>
      );
    }
    case 'table':
      return (
        <div className="doc-table">
          <table>
            {block.title && <caption>{block.title}</caption>}
            <thead>
              <tr>
                {block.columns.map((column, index) => (
                  <th key={index} scope="col" className={isNumericColumn(block.rows, index) ? 'doc-number' : undefined}>
                    {column}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {block.rows.map((row, rowIndex) => (
                <tr key={rowIndex}>
                  {row.map((cell, index) => (
                    <td key={index} className={typeof cell === 'number' ? 'doc-number' : undefined}>
                      {typeof cell === 'number' ? formatNumber(cell) : cell}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      );
    case 'chart':
      return <Chart block={block} />;
    case 'quiz':
      return (
        <ol className="doc-quiz" start={firstQuestion}>
          {block.questions.map((question, index) => (
            <li key={index}>
              <p>{question.question}</p>
              {question.options.length > 0 && (
                <ul>
                  {question.options.map((option, optionIndex) => (
                    <li key={optionIndex}>
                      {OPTION_LETTERS[optionIndex] ?? '-'}) {option}
                    </li>
                  ))}
                </ul>
              )}
              {question.answer && (
                <details>
                  <summary>Soluzione</summary>
                  {question.answer}
                </details>
              )}
            </li>
          ))}
        </ol>
      );
  }
}

export function DocumentView({ document }: DocumentViewProps) {
  const [busy, setBusy] = useState<'pdf' | 'excel' | null>(null);
  const [failed, setFailed] = useState(false);
  const tabular = hasTabularData(document);

  async function download(kind: 'pdf' | 'excel') {
    setBusy(kind);
    setFailed(false);
    try {
      // The export code and its libraries are loaded only when needed.
      const blob =
        kind === 'pdf'
          ? await (await import('./pdf')).createPdf(document)
          : await (await import('./excel')).createExcel(document);
      downloadBlob(blob, fileName(document.title, kind === 'pdf' ? 'pdf' : 'xlsx'));
    } catch (error) {
      console.error(error);
      setFailed(true);
    } finally {
      setBusy(null);
    }
  }

  // Quiz questions are numbered across the whole document, as in the PDF.
  let questionCount = 0;

  return (
    <div className="doc">
      <h3 className="doc-title">{document.title}</h3>
      {!document.dataProvidedByUser && tabular && <p className="muted">{DATA_DISCLAIMER}</p>}

      {document.blocks.map((block, index) => {
        const firstQuestion = questionCount + 1;
        if (block.type === 'quiz') questionCount += block.questions.length;
        return <Block key={index} block={block} firstQuestion={firstQuestion} />;
      })}

      <div className="doc-actions">
        <button type="button" onClick={() => void download('pdf')} disabled={busy !== null}>
          {busy === 'pdf' ? 'Creazione del PDF' : 'Scarica PDF'}
        </button>
        {tabular && (
          <button type="button" onClick={() => void download('excel')} disabled={busy !== null}>
            {busy === 'excel' ? 'Creazione del file Excel' : 'Scarica Excel'}
          </button>
        )}
      </div>
      {failed && (
        <p role="alert" className="error">
          Creazione del file non riuscita. Riprova.
        </p>
      )}
    </div>
  );
}
